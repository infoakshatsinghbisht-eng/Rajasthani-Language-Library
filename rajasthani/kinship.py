def resolve_kinship(query: str) -> Optional[KinshipTerm]:
    """
    Resolves a kinship query in English, Hindi, or Rajasthani to a KinshipTerm.
    """
    clean = query.strip().lower()
    for term in KINSHIP_DATABASE:
        if clean == term.relation_key.lower():
            return term
        if clean in term.rajasthani.lower() or clean in term.roman.lower():
            return term
        if clean in term.english.lower() or clean in term.hindi.lower():
            return term
        if any(clean in v.lower() for v in term.dialect_variants.values()):
            return term
    return None


def get_all_kinship_terms() -> List[KinshipTerm]:
    """Returns all cataloged Rajasthani kinship terms."""
    return list(KINSHIP_DATABASE)


def list_by_category(category: str) -> List[KinshipTerm]:
    """Filters kinship terms by category (paternal, maternal, affinal, sibling, descendant)."""
    return [t for t in KINSHIP_DATABASE if t.category == category]
